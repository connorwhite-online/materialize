export function spriteFrameAt(tick: number): number {
  let t =
    ((Math.floor(tick) % SPRITE_LOOP_TICKS) + SPRITE_LOOP_TICKS) %
    SPRITE_LOOP_TICKS;
  for (const [f, n] of SPRITE_SEQUENCE) {
    if (t < n) return f;
    t -= n;
  }
  return SPRITE_SEQUENCE[0][0];
}
